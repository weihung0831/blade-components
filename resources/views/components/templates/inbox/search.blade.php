    <script>
        (() => {
            const screen = document.querySelector('[data-search-screen]');

            if (!screen) {
                return;
            }

            const input = screen.querySelector('[data-query]');
            const plain = screen.querySelector('[data-query-plain]');
            const rows = [...screen.querySelectorAll('[data-thread]')];
            const empty = screen.querySelector('[data-result-empty]');
            const counter = screen.querySelector('[data-result-count]');

            const fields = ['is', 'tag', 'with', 'via', 'has', 'ref'];

            const desk = { hana: 'Hana Okabe', lena: 'Lena Kohler', idris: 'Idris Bahar' };

            const words = {
                'is:open': 'still open',
                'is:waiting': 'waiting on the customer',
                'is:snoozed': 'snoozed',
                'is:closed': 'closed',
                'is:overdue': 'past the reply promise',
                'is:unowned': 'nobody has picked it up',
                'has:file': 'something attached',
            };

            const parse = (query) => {
                const filters = [];
                const terms = [];

                query.trim().toLowerCase().split(/\s+/).filter(Boolean).forEach((piece) => {
                    const [key, ...rest] = piece.split(':');

                    if (rest.length > 0 && fields.includes(key)) {
                        filters.push([key, rest.join(':')]);
                    } else {
                        terms.push(piece);
                    }
                });

                return { filters, terms };
            };

            const keeps = (row, { filters, terms }) => {
                const minutes = row.dataset.minutes === '' ? null : Number(row.dataset.minutes);

                const passes = filters.every(([key, value]) => {
                    if (key === 'is') {
                        if (value === 'overdue') return minutes !== null && minutes < 0;
                        if (value === 'unowned') return row.dataset.owner === 'unassigned';
                        if (value === 'unread') return row.hasAttribute('data-unread');

                        return row.dataset.state === value;
                    }

                    if (key === 'tag') return row.dataset.tags.includes(value);
                    if (key === 'with') return row.dataset.owner.toLowerCase().includes(desk[value]?.toLowerCase() ?? value);
                    if (key === 'via') return row.dataset.channel === value;
                    if (key === 'has') return value === 'file' && Number(row.dataset.files) > 0;
                    if (key === 'ref') return row.dataset.ref.toLowerCase().includes(value);

                    return true;
                });

                return passes && terms.every((term) => row.dataset.search.includes(term));
            };

            const describe = ({ filters, terms }) => {
                const pieces = filters.map(([key, value]) => {
                    const token = `${key}:${value}`;

                    if (words[token]) return words[token];
                    if (key === 'tag') return `tagged ${value}`;
                    if (key === 'with') return `${desk[value] ?? value} is on it`;
                    if (key === 'via') return `came in by ${value}`;
                    if (key === 'ref') return `ref contains ${value}`;

                    return token;
                });

                if (terms.length > 0) {
                    pieces.push(`the ${terms.length > 1 ? 'words' : 'word'} “${terms.join(' ')}”`);
                }

                return pieces.length > 0 ? pieces.join(' · ') : 'everything, oldest promise first';
            };

            const run = () => {
                const query = parse(input.value);

                const shown = rows.filter((row) => {
                    const match = keeps(row, query);

                    row.classList.toggle('hidden', !match);

                    return match;
                });

                counter.textContent = shown.length;
                plain.textContent = describe(query);
                empty.classList.toggle('hidden', shown.length > 0);

                const active = input.value.trim().toLowerCase().split(/\s+/);

                screen.querySelectorAll('[data-facet]').forEach((facet) => {
                    facet.toggleAttribute('data-on', active.includes(facet.dataset.facet));

                    const tally = screen.querySelector(`[data-facet-count="${facet.dataset.facet}"]`);
                    const probe = parse(`${input.value} ${facet.dataset.facet}`);

                    tally.textContent = rows.filter((row) => keeps(row, probe)).length;
                });
            };

            const add = (token) => {
                const parts = input.value.trim().split(/\s+/).filter(Boolean);

                input.value = parts.includes(token)
                    ? parts.filter((part) => part !== token).join(' ')
                    : [...parts, token].join(' ');

                run();
            };

            screen.addEventListener('click', (event) => {
                const facet = event.target.closest('[data-facet]');
                const token = event.target.closest('[data-token]');
                const saved = event.target.closest('[data-saved]');
                const clear = event.target.closest('[data-clear]');

                if (facet) add(facet.dataset.facet);
                if (token) add(token.dataset.token);

                if (saved) {
                    input.value = saved.dataset.saved;
                    run();
                }

                if (clear) {
                    input.value = '';
                    run();
                }
            });

            input.addEventListener('input', run);

            run();
        })();
    </script>
